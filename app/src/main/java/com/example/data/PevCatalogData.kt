  fun extractFirstInt(text: String): Int =
    Regex("(\\d+)").find(text.replace(",", ""))?.groupValues?.get(1)?.toIntOrNull() ?: 0

  fun extractWh(batteryText: String): Int =
    Regex("(\\d{3,5})\\s*Wh", RegexOption.IGNORE_CASE)
      .find(batteryText.replace(",", ""))
      ?.groupValues
      ?.get(1)
      ?.toIntOrNull()
      ?: extractFirstInt(batteryText)

  fun extractPriceDouble(priceText: String): Double =
    Regex("([0-9]+(?:\\.[0-9]+)?)")
      .find(priceText.replace(",", ""))
      ?.groupValues
      ?.get(1)
      ?.toDoubleOrNull()
      ?: 0.0

  fun filterSpecCatalog(
    specs: List<PevSpecRecord> = BUILT_IN_SPECS,
    query: String = "",
    category: String = "ALL",
    minVoltage: Int = 0,
    sortMode: SpecSortMode = SpecSortMode.DEFAULT,
  ): List<PevSpecRecord> {
    val q = query.trim().lowercase()
    val filtered =
      specs.filter { s ->
        val catOk = category == "ALL" || s.category.equals(category, ignoreCase = true)
        val voltOk = minVoltage <= 0 || s.nominalVoltage >= minVoltage
        val qOk =
          q.isBlank() ||
            s.name.lowercase().contains(q) ||
            s.brand.lowercase().contains(q) ||
            s.category.lowercase().contains(q) ||
            s.motorPower.lowercase().contains(q) ||
            s.battery.lowercase().contains(q) ||
            s.tireProfile.lowercase().contains(q)
        catOk && voltOk && qOk
      }
    return when (sortMode) {
      SpecSortMode.DEFAULT -> filtered
      SpecSortMode.SPEED_DESC -> filtered.sortedByDescending { extractFirstInt(it.topSpeed) }
      SpecSortMode.RANGE_DESC -> filtered.sortedByDescending { extractFirstInt(it.range) }
      SpecSortMode.BATTERY_DESC -> filtered.sortedByDescending { extractWh(it.battery) }
      SpecSortMode.PRICE_ASC ->
        filtered.sortedBy {
          val p = extractPriceDouble(it.price)
          if (p <= 0.0) Double.MAX_VALUE else p
        }
    }
  }

  fun filterPartCatalog(
    parts: List<PevPartItem> = BUILT_IN_PARTS,
    query: String = "",
    vehicleType: String = "ALL",
    category: String = "ALL",
  ): List<PevPartItem> {
    val q = query.trim().lowercase()
    return parts.filter { p ->
      val vehOk =
        vehicleType == "ALL" ||
          p.compatibility.contains(vehicleType, ignoreCase = true) ||
          p.partName.contains(vehicleType, ignoreCase = true)
      val catOk =
        category == "ALL" ||
          p.category.equals(category, ignoreCase = true) ||
          p.partType.contains(category, ignoreCase = true)
      val qOk =
        q.isBlank() ||
          p.partName.lowercase().contains(q) ||
          p.exactDimensions.lowercase().contains(q) ||
          p.compatibility.lowercase().contains(q) ||
          p.recommendedBrands.lowercase().contains(q) ||
          p.category.lowercase().contains(q)
      vehOk && catOk && qOk
    }
  }

  fun estimateSimulatedRangeMiles(spec: PevSpecRecord, riderLbs: Double, cruiseMph: Double): Double {
    val whNum = extractWh(spec.battery).toDouble().coerceAtLeast(300.0)
    val burnWhPerMi = (21.0 + (riderLbs - 165.0) * 0.12 + cruiseMph * 0.68).coerceAtLeast(14.0)
    return ((whNum / burnWhPerMi) * 10.0).roundToInt() / 10.0
  }
